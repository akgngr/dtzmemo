def walk_erfahrung(data):
    out = []
    def visit(node, cat_hint):
        if isinstance(node, dict):
            if "Almanca" in node and "Türkçe" in node:
                a = node["Almanca"]
                t = node["Türkçe"]
                if isinstance(a, str) and isinstance(t, str):
                    out.append((cat_hint, a, t))
                elif isinstance(a, list) and isinstance(t, list):
                    for i in range(min(len(a), len(t))):
                        out.append((cat_hint, a[i], t[i]))
                return
            if "Örnekler" in node and isinstance(node["Örnekler"], list):
                for e in node["Örnekler"]:
                    if isinstance(e, dict) and "Almanca" in e and "Türkçe" in e:
                        out.append((cat_hint, e["Almanca"], e["Türkçe"]))
                return
            for k, v in node.items():
                if isinstance(v, (dict, list)):
                    visit(v, k if isinstance(v, dict) and "Örnekler" in v else cat_hint)
        elif isinstance(node, list):
            for item in node:
                visit(item, cat_hint)
    visit(data.get("B1_BILDBESCHREIBUNG_ERFAHRUNG", {}), "Erfahrung")
