def clean_token(t: str) -> str:
    """Strip surrounding punctuation from a token."""
    return re.sub(r'^[^\wäöüÄÖÜß]+|[^\wäöüÄÖÜß]+$', '', t)


def is_useful_german(w: str) -> bool:
    if not w:
        return False
    if len(w) < 2:
        return False
    if w.isdigit():
        return False
    if re.fullmatch(r'[^\wäöüÄÖÜß]+', w):
        return False
    if w.lower() in GERMAN_STOPWORDS:
        return False
    return True


def tokenize(s: str):
    return [clean_token(t) for t in s.split()]


