def main():
    brief_path = UPLOAD / "brief.json"
    bild_path = UPLOAD / "bild.json"
    erfahrung_path = UPLOAD / "bild-erfahrung.json"

    all_pairs = []
    with open(brief_path, encoding="utf-8") as f:
        all_pairs.extend(walk_brief(json.load(f)))
    with open(bild_path, encoding="utf-8") as f:
        all_pairs.extend(walk_bild(json.load(f)))
    with open(erfahrung_path, encoding="utf-8") as f:
        all_pairs.extend(walk_erfahrung(json.load(f)))

    print(f"Total sentence pairs: {len(all_pairs)}")

    # Pass 1: collect all unique German words appearing in the sentences
    word_to_cats = {}  # word_lower -> (display_form, set_of_cats)
    for cat_raw, ger_sent, tr_sent in all_pairs:
        if isinstance(ger_sent, list):
            ger_sent = " ".join(str(x) for x in ger_sent)
        if not isinstance(ger_sent, str):
            continue
        for tok in tokenize(ger_sent):
            if not is_useful_german(tok):
                continue
            key = tok  # preserve original case for display
            lower = tok.lower()
            if lower not in word_to_cats:
                word_to_cats[lower] = (key, set())
            word_to_cats[lower][1].add(norm_cat(cat_raw))

    print(f"Unique useful German words found in sentences: {len(word_to_cats)}")

    # Pass 2: build the word-pair list using the curated dictionary
    # Prefer the case form that matches the dictionary key exactly.
    result = []
    seen_lower = set()
    miss_count = 0
    for lower, (display, cats) in word_to_cats.items():
        # Try exact case match first
        tr = GERMAN_TR_DICT.get(display)
        if not tr:
            # Try lowercase
            tr = GERMAN_TR_DICT.get(lower)
        if not tr:
            # Try capitalized first letter
            cap = display[0].upper() + display[1:]
            tr = GERMAN_TR_DICT.get(cap)
        if not tr:
            miss_count += 1
            continue
        if lower in seen_lower:
            continue
        seen_lower.add(lower)
        # Pick the first category (alphabetical) as primary
        cat = sorted(cats)[0] if cats else "diger"
        result.append({
            "id": "",
            "german": display,
            "turkish": tr,
            "category": cat,
        })

    print(f"Words matched to translations: {len(result)}")
    print(f"Words skipped (no translation): {miss_count}")

    # Sort by category then alphabetical
    result.sort(key=lambda x: (x["category"], x["german"].lower()))
    for i, item in enumerate(result, start=1):
        item["id"] = f"v{i}"

    out_obj = {
        "_meta": {
            "source_files": ["upload/brief.json", "upload/bild.json", "upload/bild-erfahrung.json"],
            "description": "Bu dosya brief.json, bild.json ve bild-erfahrung.json dosyalarındaki cümlelerin içinden çıkarılan bireysel Almanca kelimelerini içerir. Türkçe karşılıkları küratörlü bir B1 seviye sözlükten gelir. Orijinal JSON dosyaları değiştirilmemiştir.",
            "extraction_method": "Tokenize German sentences -> filter stopwords/punctuation -> lookup Turkish translation in curated B1 dictionary",
            "total_words": len(result),
        },
        "words": result,
    }

    OUT.parent.mkdir(parents=True, exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(out_obj, f, ensure_ascii=False, indent=2)
    print(f"Wrote: {OUT}")

    # Print category breakdown
    from collections import Counter
    cats = Counter(w["category"] for w in result)
    print("Category breakdown:")
    for c, n in cats.most_common():
        print(f"  {c:25} {n}")


